#!/usr/bin/env python3
"""Draws the layer demo's vector sprite, an emblem in the theme's colours, twice: as an SVG
(data/fgimage/emblem.svg, which layerExVector draws again at every size and angle) and as a
PNG of the same picture at its own size (data/fgimage/emblem_bitmap.png), which layer.ks
zooms next to it to show the difference.

Both come from one list of shapes (circles, a star, tick marks; solid colours and linear or
radial gradients): the SVG writes them out, and the PNG is drawn here, SS times larger and
averaged down. No text: layerExVector's ThorVG has no fonts to draw SVG <text> with.

usage: python3 tools/assets/make_vector.py
"""
import math, os

import numpy as np
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "data", "fgimage")
SIZE = 320
SS = 6  # supersampling for the PNG

VIOLET = (80, 37, 255)   # the theme's borders and hard shadows (make_ui.py)
LAV = (166, 144, 255)    # its panels
NAVY = (1, 0, 98)        # its text outlines
WHITE = (255, 255, 255)


def radial(cx, cy, r, stops):
    return ("radial", cx, cy, r, stops)


def linear(x1, y1, x2, y2, stops):
    return ("linear", x1, y1, x2, y2, stops)


def star_points(cx, cy, outer, inner, n=5, rot=-90):
    pts = []
    for i in range(n * 2):
        a = math.radians(rot + i * 180 / n)
        r = outer if i % 2 == 0 else inner
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return pts


def emblem():
    """The shapes, back to front: (kind, geometry, fill, stroke), stroke = (colour, width)"""
    c = 156.0
    shapes = [
        ("circle", (c + 8, c + 8, 151), VIOLET, None),  # the hard shadow
        ("circle", (c, c, 148), radial(c, c, 148, [(0, (248, 245, 255)), (0.62, (204, 192, 255)), (1, LAV)]),
         (VIOLET, 6)),
    ]
    ticks = []
    for k in range(48):
        a = math.radians(k * 7.5)
        r0, r1 = (127, 143) if k % 4 == 0 else (131, 139)
        ticks.append((c + r0 * math.cos(a), c + r0 * math.sin(a), c + r1 * math.cos(a), c + r1 * math.sin(a)))
    shapes += [
        ("lines", ticks, None, (VIOLET, 2)),
        ("circle", (c, c, 122), None, (VIOLET, 2.5)),
        ("circle", (c, c, 116), None, (WHITE, 1.5)),
        ("circle", (c, c, 98), radial(c - 16, c - 20, 118, [(0, (136, 104, 255)), (1, VIOLET)]), (WHITE, 3)),
    ]
    for k in range(8):
        a = math.radians(k * 45 + 22.5)
        shapes.append(("circle", (c + 107 * math.cos(a), c + 107 * math.sin(a), 4), WHITE, (VIOLET, 1.5)))
    shapes += [
        ("polygon", star_points(c, c + 4, 82, 34), linear(c, c - 78, c, c + 70, [(0, WHITE), (1, (222, 212, 255))]),
         (NAVY, 4)),
        ("polygon", star_points(c, c + 4, 46, 19), None, (VIOLET, 1.5)),
        ("circle", (c, c + 4, 6), VIOLET, None),
    ]
    return shapes


# --- SVG ---------------------------------------------------------------------------------
def hexc(col):
    return "#%02x%02x%02x" % col


def svg(shapes):
    defs, body = [], []

    def paint(p):
        if p is None:
            return "none"
        if isinstance(p[0], str):
            gid = "g%d" % len(defs)
            stops = "".join('<stop offset="%g" stop-color="%s"/>' % (o, hexc(col)) for o, col in p[-1])
            if p[0] == "radial":
                defs.append('<radialGradient id="%s" gradientUnits="userSpaceOnUse" cx="%.2f" cy="%.2f" r="%.2f">%s'
                            '</radialGradient>' % ((gid,) + p[1:4] + (stops,)))
            else:
                defs.append('<linearGradient id="%s" gradientUnits="userSpaceOnUse" x1="%.2f" y1="%.2f" x2="%.2f" '
                            'y2="%.2f">%s</linearGradient>' % ((gid,) + p[1:5] + (stops,)))
            return "url(#%s)" % gid
        return hexc(p)

    for kind, geo, fill, stroke in shapes:
        st = ' stroke="%s" stroke-width="%g"' % (hexc(stroke[0]), stroke[1]) if stroke else ""
        if kind == "circle":
            body.append('<circle cx="%.2f" cy="%.2f" r="%.2f" fill="%s"%s/>' % (geo + (paint(fill), st)))
        elif kind == "polygon":
            pts = " ".join("%.2f,%.2f" % p for p in geo)
            body.append('<polygon points="%s" fill="%s"%s stroke-linejoin="round"/>' % (pts, paint(fill), st))
        elif kind == "lines":
            d = " ".join("M%.2f %.2fL%.2f %.2f" % t for t in geo)
            body.append('<path d="%s" fill="none"%s/>' % (d, st))
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" width="%d" height="%d">\n'
            '<!-- generated by tools/assets/make_vector.py -->\n<defs>%s</defs>\n%s\n</svg>\n'
            % (SIZE, SIZE, SIZE, SIZE, "".join(defs), "\n".join(body)))


# --- the PNG -----------------------------------------------------------------------------
def mask(draw_fn):
    m = Image.new("L", (SIZE * SS, SIZE * SS), 0)
    draw_fn(ImageDraw.Draw(m))
    return np.asarray(m, np.float32) / 255


def disc(d, cx, cy, r):
    d.ellipse([(cx - r) * SS, (cy - r) * SS, (cx + r) * SS, (cy + r) * SS], fill=255)


def paint_rgb(p, xs, ys):
    """the colour of paint p at every pixel centre (xs, ys in picture units)"""
    if not isinstance(p[0], str):
        return np.broadcast_to(np.array(p, np.float32), xs.shape + (3,))
    if p[0] == "radial":
        _, cx, cy, r, stops = p
        t = np.hypot(xs - cx, ys - cy) / r
    else:
        _, x1, y1, x2, y2, stops = p
        dx, dy = x2 - x1, y2 - y1
        t = ((xs - x1) * dx + (ys - y1) * dy) / (dx * dx + dy * dy)
    t = np.clip(t, 0, 1)
    offs = [o for o, _ in stops]
    return np.stack([np.interp(t, offs, [col[i] for _, col in stops]) for i in range(3)], -1).astype(np.float32)


def bitmap(shapes):
    n = SIZE * SS
    ys, xs = (np.mgrid[0:n, 0:n].astype(np.float32) + 0.5) / SS
    pre = np.zeros((n, n, 4), np.float32)  # premultiplied RGBA, 0-1

    def over(p, m):
        rgb = paint_rgb(p, xs, ys) / 255
        a = m[..., None]
        pre[..., :3] = rgb * a + pre[..., :3] * (1 - a)
        pre[..., 3:] = a + pre[..., 3:] * (1 - a)

    for kind, geo, fill, stroke in shapes:
        if kind == "circle":
            cx, cy, r = geo
            if fill is not None:
                over(fill, mask(lambda d: disc(d, cx, cy, r)))
            if stroke:
                w = stroke[1] / 2
                over(stroke[0], np.clip(mask(lambda d: disc(d, cx, cy, r + w)) - mask(lambda d: disc(d, cx, cy, r - w)), 0, 1))
        elif kind == "polygon":
            pts = [(x * SS, y * SS) for x, y in geo]
            if fill is not None:
                over(fill, mask(lambda d: d.polygon(pts, fill=255)))
            if stroke:
                w = stroke[1]

                def outline(d):
                    d.line(pts + pts[:1], fill=255, width=int(round(w * SS)))
                    for x, y in geo:  # round joins
                        disc(d, x, y, w / 2)
                over(stroke[0], mask(outline))
        elif kind == "lines":
            over(stroke[0], mask(lambda d: [d.line([(x0 * SS, y0 * SS), (x1 * SS, y1 * SS)], fill=255,
                                                   width=int(round(stroke[1] * SS))) for x0, y0, x1, y1 in geo]))
    pre = pre.reshape(SIZE, SS, SIZE, SS, 4).mean((1, 3))
    a = pre[..., 3:]
    rgb = np.where(a > 0, pre[..., :3] / np.maximum(a, 1e-6), 0)
    return Image.fromarray(np.clip(np.concatenate([rgb, a], -1) * 255 + 0.5, 0, 255).astype(np.uint8), "RGBA")


def main():
    os.makedirs(OUT, exist_ok=True)
    shapes = emblem()
    with open(os.path.join(OUT, "emblem.svg"), "w", newline="\n") as f:
        f.write(svg(shapes))
    bitmap(shapes).save(os.path.join(OUT, "emblem_bitmap.png"), optimize=True)
    print("wrote data/fgimage/emblem.svg and data/fgimage/emblem_bitmap.png")


if __name__ == "__main__":
    main()
